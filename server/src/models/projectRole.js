import mongoose from 'mongoose';

const projectRoleSchema = new mongoose.Schema({
  projectId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Project',
    required: true,
    index: true
  },
  userId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
    index: true
  },
  role: {
    type: String,
    required: true,
    trim: true
  },
  isActive: {
    type: Boolean,
    default: true
  }
}, {
  timestamps: true
});

// Unique per user per project
projectRoleSchema.index({ projectId: 1, userId: 1 }, { unique: true });

export default mongoose.model('ProjectRole', projectRoleSchema);
